// Package specgrammar turns the specification inventories vendored under
// testdata/spec into the Go tables the validator's grammar check reads
// (validator/grammar_tables.go).
//
// The inventories stay test data: no library code opens them at run time.
// This package runs at `go generate` time, through internal/cmd/gengrammar,
// and from a test that fails when the checked-in tables no longer match what
// the inventories generate.
//
// Each version is reduced to the same shape: the level-0 record tags, and for
// every structure its payload datatype, its enumeration (if any) and the
// substructures it permits with their cardinalities. 7.0 reads FamilySearch's
// own extracted files; 5.5 and 5.5.1 read this project's transcription of the
// printed grammar (testdata/spec/README.md), whose payloads name primitives
// that primitives.tsv defines.
package specgrammar

import (
	"bufio"
	"bytes"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

// v7Prefix is stripped from every 7.0 structure URI to form its identifier.
const v7Prefix = "https://gedcom.io/terms/v7/"

// Payload kinds, named as the validator's payloadKind constants are.
const (
	kindText          = "payloadText"
	kindNone          = "payloadNone"
	kindYNull         = "payloadYNull"
	kindPointer       = "payloadPointer"
	kindPointerOrNull = "payloadPointerOrNull"
	kindInteger       = "payloadInteger"
	kindLanguage      = "payloadLanguage"
	kindEnum          = "payloadEnum"
	kindEnumList      = "payloadEnumList"
	kindDateExact     = "payloadDateExact"
	kindTime          = "payloadTime"
	kindAge           = "payloadAge"
)

// Enumeration openness, named as the validator's constants are.
const (
	openClosed = "enumClosed"
	openAny    = "enumOpen"
	openParen  = "enumOpenParenthesized"
)

// child is one permitted substructure.
type child struct {
	tag, id  string
	min, max int // max -1 is unbounded
}

// structure is one structure type.
type structure struct {
	payload string
	enum    []string
	open    string
	kids    []child
}

// table is one version's grammar.
type table struct {
	name     string // Go variable name
	version  string
	foldCase bool
	records  map[string]string // level-0 tag -> structure id
	structs  map[string]*structure
}

func (t *table) get(id string) *structure {
	s := t.structs[id]
	if s == nil {
		s = &structure{payload: kindNone, open: openClosed}
		t.structs[id] = s
	}
	return s
}

// Generate reads the inventories under specDir (testdata/spec) and returns
// the gofmt-formatted source of validator/grammar_tables.go.
func Generate(specDir string) ([]byte, error) {
	t55, err := load55(filepath.Join(specDir, "gedcom-5.5"), "grammar55", "5.5")
	if err != nil {
		return nil, err
	}
	t551, err := load55(filepath.Join(specDir, "gedcom-5.5.1"), "grammar551", "5.5.1")
	if err != nil {
		return nil, err
	}
	t70, err := load70(filepath.Join(specDir, "gedcom-7.0"))
	if err != nil {
		return nil, err
	}

	var b bytes.Buffer
	b.WriteString("// Code generated by internal/cmd/gengrammar from testdata/spec; DO NOT EDIT.\n\n")
	b.WriteString("package validator\n")
	for _, t := range []*table{t55, t551, t70} {
		emit(&b, t)
	}
	out, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated source: %w", err)
	}
	return out, nil
}

func emit(b *bytes.Buffer, t *table) {
	fmt.Fprintf(b, "\nvar %s = &grammarTable{\nversion: %q,\nfoldCase: %t,\nrecords: map[string]string{\n", t.name, t.version, t.foldCase)
	for _, tag := range sortedKeys(t.records) {
		fmt.Fprintf(b, "%q: %q,\n", tag, t.records[tag])
	}
	b.WriteString("},\nstructures: map[string]*structureDef{\n")
	for _, id := range sortedKeys(t.structs) {
		s := t.structs[id]
		fmt.Fprintf(b, "%q: {payload: %s", id, s.payload)
		if len(s.enum) > 0 {
			b.WriteString(", enum: []string{")
			for i, v := range s.enum {
				if i > 0 {
					b.WriteString(", ")
				}
				fmt.Fprintf(b, "%q", v)
			}
			b.WriteString("}")
		}
		if s.open != openClosed {
			fmt.Fprintf(b, ", open: %s", s.open)
		}
		if len(s.kids) > 0 {
			b.WriteString(", children: map[string][]childDef{\n")
			byTag := map[string][]child{}
			for _, k := range s.kids {
				byTag[k.tag] = append(byTag[k.tag], k)
			}
			for _, tag := range sortedKeys(byTag) {
				fmt.Fprintf(b, "%q: {", tag)
				for i, k := range byTag[tag] {
					if i > 0 {
						b.WriteString(", ")
					}
					fmt.Fprintf(b, "{%q, %d, %d}", k.id, k.min, k.max)
				}
				b.WriteString("},\n")
			}
			b.WriteString("}")
		}
		b.WriteString("},\n")
	}
	b.WriteString("},\n}\n")
}

func sortedKeys[V any](m map[string]V) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}

// readTSV returns the rows of a tab-separated file after its header row,
// checking that every row has want columns.
func readTSV(path string, want int) ([][]string, error) {
	data, err := os.ReadFile(path) // #nosec G304 -- a vendored inventory under the spec directory
	if err != nil {
		return nil, err
	}
	var rows [][]string
	sc := bufio.NewScanner(bytes.NewReader(data))
	sc.Buffer(make([]byte, 0, 64*1024), 1024*1024)
	for n := 1; sc.Scan(); n++ {
		line := strings.TrimRight(sc.Text(), "\r")
		if n == 1 || line == "" {
			continue
		}
		fields := strings.Split(line, "\t")
		if len(fields) != want {
			return nil, fmt.Errorf("%s:%d: %d columns, want %d", path, n, len(fields), want)
		}
		rows = append(rows, fields)
	}
	return rows, sc.Err()
}

// parseCardinality reads "1:1", "0:M" or "{0:3}" as min and max (-1 for M).
func parseCardinality(s string) (lo, hi int, err error) {
	s = strings.TrimSuffix(strings.TrimPrefix(s, "{"), "}")
	a, b, ok := strings.Cut(s, ":")
	if !ok {
		return 0, 0, fmt.Errorf("cardinality %q", s)
	}
	if lo, err = strconv.Atoi(a); err != nil {
		return 0, 0, fmt.Errorf("cardinality %q: %w", s, err)
	}
	if b == "M" {
		return lo, -1, nil
	}
	if hi, err = strconv.Atoi(b); err != nil {
		return 0, 0, fmt.Errorf("cardinality %q: %w", s, err)
	}
	return lo, hi, nil
}

// addChildren reads substructures.tsv and cardinalities.tsv, both keyed by
// (superstructure, structure), into t. A row with no superstructure is a
// level-0 record.
func addChildren(t *table, dir string, id func(string) string) error {
	subs, err := readTSV(filepath.Join(dir, "substructures.tsv"), 3)
	if err != nil {
		return err
	}
	cards, err := readTSV(filepath.Join(dir, "cardinalities.tsv"), 3)
	if err != nil {
		return err
	}
	card := map[[2]string]string{}
	for _, r := range cards {
		card[[2]string{id(r[0]), id(r[1])}] = r[2]
	}
	for _, r := range subs {
		super, tag, sub := id(r[0]), r[1], id(r[2])
		t.get(sub)
		if super == "" {
			t.records[tag] = sub
			continue
		}
		c, ok := card[[2]string{super, sub}]
		if !ok {
			return fmt.Errorf("%s: no cardinality for %s under %s", dir, sub, super)
		}
		lo, hi, err := parseCardinality(c)
		if err != nil {
			return fmt.Errorf("%s: %s under %s: %w", dir, sub, super, err)
		}
		s := t.get(super)
		s.kids = append(s.kids, child{tag: tag, id: sub, min: lo, max: hi})
	}
	for _, s := range t.structs {
		sort.SliceStable(s.kids, func(i, j int) bool {
			if s.kids[i].tag != s.kids[j].tag {
				return s.kids[i].tag < s.kids[j].tag
			}
			return s.kids[i].id < s.kids[j].id
		})
	}
	return nil
}

func load70(dir string) (*table, error) {
	t := &table{name: "grammar70", version: "7.0", records: map[string]string{}, structs: map[string]*structure{}}
	id := func(s string) string { return strings.TrimPrefix(s, v7Prefix) }
	if err := addChildren(t, dir, id); err != nil {
		return nil, err
	}

	sets := map[string][]string{}
	setRows, err := readTSV(filepath.Join(dir, "enumerationsets.tsv"), 2)
	if err != nil {
		return nil, err
	}
	for _, r := range setRows {
		sets[r[0]] = append(sets[r[0]], enumTag(r[1]))
	}
	enumRows, err := readTSV(filepath.Join(dir, "enumerations.tsv"), 2)
	if err != nil {
		return nil, err
	}
	enums := map[string][]string{}
	for _, r := range enumRows {
		values := append([]string(nil), sets[r[1]]...)
		if len(values) == 0 {
			return nil, fmt.Errorf("%s: enumeration set %s is empty", dir, r[1])
		}
		sort.Strings(values)
		enums[id(r[0])] = values
	}

	payloads, err := readTSV(filepath.Join(dir, "payloads.tsv"), 2)
	if err != nil {
		return nil, err
	}
	for _, r := range payloads {
		s := t.get(id(r[0]))
		s.payload = payload70(r[1])
		if s.payload == kindEnum || s.payload == kindEnumList {
			if s.enum = enums[id(r[0])]; s.enum == nil {
				return nil, fmt.Errorf("%s: %s is an enumeration with no set", dir, r[0])
			}
		}
	}
	return t, nil
}

// enumTag returns the tag a 7.0 enumeration value URI stands for: its last
// path segment without "enum-", and without the structure prefix that keeps
// URIs unique ("enum-ADOP-HUSB" is HUSB, "INDI-RELI" is RELI).
func enumTag(uri string) string {
	s := strings.TrimPrefix(strings.TrimPrefix(uri, v7Prefix), "enum-")
	if i := strings.LastIndex(s, "-"); i >= 0 {
		s = s[i+1:]
	}
	return s
}

func payload70(p string) string {
	switch {
	case p == "":
		return kindNone
	case p == "Y|<NULL>":
		return kindYNull
	case strings.HasPrefix(p, "@<"):
		return kindPointer
	}
	switch strings.TrimPrefix(p, v7Prefix) {
	case "http://www.w3.org/2001/XMLSchema#nonNegativeInteger":
		return kindInteger
	case "http://www.w3.org/2001/XMLSchema#Language":
		return kindLanguage
	case "type-Enum":
		return kindEnum
	case "type-List#Enum":
		return kindEnumList
	case "type-Date#exact":
		return kindDateExact
	case "type-Time":
		return kindTime
	case "type-Age":
		return kindAge
	}
	return kindText
}

// primitive55 maps the 5.5.x primitives whose definitions are a datatype
// rather than a value list to that datatype. The transcription records only
// their size, so which datatype each is was read from the grammar chapter.
var primitive55 = map[string]string{
	"CHANGE_DATE":        kindDateExact, // := <DATE_EXACT>
	"TRANSMISSION_DATE":  kindDateExact, // := <DATE_EXACT>
	"TIME_VALUE":         kindTime,
	"AGE_AT_EVENT":       kindAge,
	"COUNT_OF_CHILDREN":  kindInteger,
	"COUNT_OF_MARRIAGES": kindInteger,
}

type primitive struct {
	values       []string
	placeholders []string
}

func load55(dir, name, version string) (*table, error) {
	t := &table{name: name, version: version, foldCase: true, records: map[string]string{}, structs: map[string]*structure{}}
	if err := addChildren(t, dir, func(s string) string { return s }); err != nil {
		return nil, err
	}

	prims := map[string]primitive{}
	rows, err := readTSV(filepath.Join(dir, "primitives.tsv"), 4)
	if err != nil {
		return nil, err
	}
	for _, r := range rows {
		prims[r[0]] = primitive{values: splitBar(r[2]), placeholders: splitBar(r[3])}
	}

	payloads, err := readTSV(filepath.Join(dir, "payloads.tsv"), 2)
	if err != nil {
		return nil, err
	}
	for _, r := range payloads {
		s := t.get(r[0])
		s.payload, s.enum, s.open = payload55(r[1], prims)
	}
	return t, nil
}

func splitBar(s string) []string {
	if s == "" {
		return nil
	}
	return strings.Split(s, "|")
}

// payload55 classifies a 5.5.x payload as printed in the grammar.
func payload55(p string, prims map[string]primitive) (kind string, enum []string, open string) {
	open = openClosed
	compact := strings.ReplaceAll(p, " ", "")
	switch {
	case compact == "[Y|<NULL>]":
		return kindYNull, nil, open
	case strings.HasPrefix(compact, "@<"):
		return kindPointer, nil, open
	case strings.HasPrefix(compact, "[@<") && strings.HasSuffix(compact, "|<NULL>]"):
		return kindPointerOrNull, nil, open
	}
	if !strings.HasPrefix(p, "<") || !strings.HasSuffix(p, ">") {
		return kindText, nil, open
	}
	name := strings.TrimSuffix(strings.TrimPrefix(p, "<"), ">")
	if k, ok := primitive55[name]; ok {
		return k, nil, open
	}
	values, open, ok := resolveValues(name, prims, map[string]bool{})
	if !ok || len(values) == 0 {
		return kindText, nil, openClosed
	}
	return kindEnum, values, open
}

// resolveValues collects a primitive's literal values, following placeholders
// that name another primitive. ok is false when a placeholder names something
// that is not a value list (a date grammar, say), so the primitive is not an
// enumeration.
func resolveValues(name string, prims map[string]primitive, seen map[string]bool) (values []string, open string, ok bool) {
	p, found := prims[name]
	if !found || seen[name] {
		return nil, openClosed, false
	}
	seen[name] = true
	open = openClosed
	values = append(values, p.values...)
	for _, ph := range p.placeholders {
		switch {
		case ph == "<user defined>":
			open = openAny
		case strings.HasPrefix(ph, "(<") && strings.HasSuffix(ph, ">)"):
			open = openParen
		case strings.HasPrefix(ph, "<") && strings.HasSuffix(ph, ">"):
			more, o, ok := resolveValues(strings.Trim(ph, "<>"), prims, seen)
			if !ok {
				return nil, openClosed, false
			}
			values = append(values, more...)
			if o != openClosed {
				open = o
			}
		default:
			return nil, openClosed, false
		}
	}
	seen[name] = false
	return dedupe(values), open, true
}

func dedupe(values []string) []string {
	out := make([]string, 0, len(values))
	seen := map[string]bool{}
	for _, v := range values {
		if !seen[v] {
			seen[v] = true
			out = append(out, v)
		}
	}
	sort.Strings(out)
	return out
}
