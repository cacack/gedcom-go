package specgraph

import (
	"bytes"
	"fmt"
	"go/format"
	"path/filepath"
	"slices"
)

// Placement is where one version allows each standard tag, keyed by the tag
// of the structure it sits under rather than by structure: a decoder that
// meets a line knows its parent's tag, not which of the structures sharing
// that tag the parent is.
type Placement struct {
	// Tags is every tag the version defines anywhere, sorted.
	Tags []string
	// Records maps a top-level tag (a record type, HEAD) to the tags its
	// structure allows at level 1, sorted.
	Records map[string][]string
	// Children maps a tag to the tags allowed under any structure below the
	// top level that has it, sorted.
	Children map[string][]string
}

// PlacementOf reduces g to tag placement. A tag is allowed under a parent
// tag when any structure reached by that tag allows it, so a tag naming
// several structures (a SOUR citation and the SOUR under a header) permits
// the union of their substructures.
func PlacementOf(g Graph) Placement {
	type reach struct {
		tag string
		top bool
	}
	reached := map[string][]reach{}
	tags := map[string]bool{}
	for super, children := range g {
		for tag, structures := range children {
			tags[tag] = true
			for _, s := range structures {
				reached[s] = append(reached[s], reach{tag, super == ""})
			}
		}
	}

	p := Placement{Tags: sortedKeys(tags), Records: map[string][]string{}, Children: map[string][]string{}}
	for super, children := range g {
		if super == "" {
			continue
		}
		for _, r := range reached[super] {
			into := p.Children
			if r.top {
				into = p.Records
			}
			for tag := range children {
				if !slices.Contains(into[r.tag], tag) {
					into[r.tag] = append(into[r.tag], tag)
				}
			}
		}
	}
	for _, m := range []map[string][]string{p.Records, p.Children} {
		for _, list := range m {
			slices.Sort(list)
		}
	}
	return p
}

// GeneratePlacement returns the Go source of the decoder's tag placement
// tables, read from the spec directory (testdata/spec) for 5.5, 5.5.1 and
// 7.0. Like Generate, its output is gofmt-formatted and depends only on the
// files.
func GeneratePlacement(specDir string) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString(`// Code generated by internal/cmd/genplacement from testdata/spec/*/substructures.tsv; DO NOT EDIT.

package decoder

`)
	for _, v := range []struct{ dir, prefix, name, version string }{
		{"gedcom-5.5", "", "placement55", "5.5"},
		{"gedcom-5.5.1", "", "placement551", "5.5.1"},
		{"gedcom-7.0", V7Prefix, "placement70", "7.0"},
	} {
		g, err := Load(filepath.Join(specDir, v.dir, "substructures.tsv"), v.prefix)
		if err != nil {
			return nil, err
		}
		writePlacement(&b, v.name, v.version, PlacementOf(g))
	}
	return format.Source(b.Bytes())
}

func writePlacement(b *bytes.Buffer, name, version string, p Placement) {
	fmt.Fprintf(b, "// %s is where GEDCOM %s allows each standard tag.\nvar %s = &tagPlacement{\n", name, version, name)
	b.WriteString("\ttags: []string{")
	writeStrings(b, p.Tags)
	b.WriteString("},\n")
	for _, m := range []struct {
		field string
		tags  map[string][]string
	}{{"records", p.Records}, {"children", p.Children}} {
		fmt.Fprintf(b, "\t%s: map[string][]string{\n", m.field)
		for _, tag := range sortedKeys(m.tags) {
			fmt.Fprintf(b, "\t\t%q: {", tag)
			writeStrings(b, m.tags[tag])
			b.WriteString("},\n")
		}
		b.WriteString("\t},\n")
	}
	b.WriteString("}\n\n")
}

func writeStrings(b *bytes.Buffer, list []string) {
	for i, s := range list {
		if i > 0 {
			b.WriteString(", ")
		}
		fmt.Fprintf(b, "%q", s)
	}
}
